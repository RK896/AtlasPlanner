"""Save planner replies as Markdown files."""
import re
from datetime import datetime
from pathlib import Path

MAX_SLUG_LENGTH = 40


def slugify(text: str) -> str:
    """'My Lisbon Trip!' -> 'my-lisbon-trip'."""
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return slug[:MAX_SLUG_LENGTH].rstrip("-") or "trip"


def save_itinerary(content: str, directory: Path, name: str, now: datetime | None = None) -> Path:
    """Write `content` to <directory>/<name>-<timestamp>.md and return the path."""
    if not content.strip():
        raise ValueError("Nothing to save yet: ask the planner for a trip first")
    timestamp = (now or datetime.now()).strftime("%Y%m%d-%H%M%S")
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"{slugify(name)}-{timestamp}.md"
    header = f"<!-- Generated by AtlasPlanner on {timestamp} -->\n\n"
    path.write_text(header + content, encoding="utf-8")
    return path
